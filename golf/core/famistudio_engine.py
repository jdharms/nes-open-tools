"""Build the FamiStudio sound engine and one exported song into a blob for bank 3.

A proof of concept (docs/famistudio_music.md). The blob is the engine's own ca65
source, unmodified except for the final copy from its output buffer to the APU,
plus a wrapper that answers the game's music requests. `famistudio_music`
(`golf/core/patches/famistudio_music.py`) places it and hooks it in.

Needs `ca65` and `ld65` on the path, the engine source (`famistudio_ca65.s` and
its `NoteTables/`) and a song exported from FamiStudio as "FamiStudio Music
Code" in ca65 format. Neither the engine nor a song is in the repository.
"""

from __future__ import annotations

import re
import shutil
import subprocess
import tempfile
from dataclasses import dataclass
from pathlib import Path

#: Where the blob goes: the CPU opponents' recorded shots in bank 3, which
#: nothing reaches once match play is off the menu (docs/opponent_shots.md).
BLOB_BANK = 3
BLOB_ORIGIN = 0xA923
BLOB_END = 0xBEE7  # inclusive

#: The engine's RAM: score records of save slots 2-26 (`$677C`-`$6C0D`), which
#: a `menu_trim` ROM never selects (docs/rom_map.md, "Round save slots").
RAM_ORIGIN = 0x677C
RAM_LIMIT = 0x6C0D

#: Zero page the engine borrows. It only uses these inside its own routines, so
#: the wrapper saves them before each call and restores them after.
ZP_ORIGIN = 0x00
ZP_SIZE = 8

#: The music ID the engine answers: the theme `CourseBgmTable` gives course 0,
#: the only course a `menu_trim` ROM plays.
MUSIC_ID = 0x03

ENGINE_SOURCE = "famistudio_ca65.s"

_CONFIG = f"""\
; Generated by golf.core.famistudio_engine. Every 2A03 feature, FamiStudio tempo.
FAMISTUDIO_CFG_EXTERNAL          = 1
.define FAMISTUDIO_CA65_ZP_SEGMENT   FSZP
.define FAMISTUDIO_CA65_RAM_SEGMENT  FSRAM
.define FAMISTUDIO_CA65_CODE_SEGMENT FSCODE
FAMISTUDIO_CFG_NTSC_SUPPORT      = 1
; Sound effect support is on for its output buffer alone: the engine then
; writes the APU in one place, which is where the game's own effects are given
; way to. No stream is ever played.
FAMISTUDIO_CFG_SFX_SUPPORT       = 1
FAMISTUDIO_CFG_SFX_STREAMS       = 0
; Off: the sample channel is the game's (DmcUpdate), and the engine writes it
; directly, not through the output buffer.
FAMISTUDIO_CFG_DPCM_SUPPORT      = 0
; Off: with it on the engine also drives the sweep units and $4017, which the
; game's effects use.
FAMISTUDIO_CFG_SMOOTH_VIBRATO    = 0
FAMISTUDIO_USE_VOLUME_TRACK      = 1
FAMISTUDIO_USE_VOLUME_SLIDES     = 1
FAMISTUDIO_USE_PITCH_TRACK       = 1
FAMISTUDIO_USE_SLIDE_NOTES       = 1
FAMISTUDIO_USE_NOISE_SLIDE_NOTES = 1
FAMISTUDIO_USE_VIBRATO           = 1
FAMISTUDIO_USE_ARPEGGIO          = 1
FAMISTUDIO_USE_DUTYCYCLE_EFFECT  = 1
FAMISTUDIO_USE_PHASE_RESET       = 1
FAMISTUDIO_USE_RELEASE_NOTES     = 1

MusicRequest     = $F4  ; $01-$17 start a track, bit 7 stops; cleared each frame
SfxSlot1Playing  = $F5  ; the effect holding pulse 1, 0 when free
SfxSlot2Playing  = $F6  ; pulse 2
SfxSlot3Playing  = $F7  ; noise
PlayingMusicID   = $F9
MusicSuspendFlag = $FF
MUSIC_ID         = ${MUSIC_ID:02X}
ZP_SIZE          = {ZP_SIZE}

.import __FSRAM_RUN__, __FSRAM_SIZE__

.segment "FSCODE"

; Called from the NMI once a frame with this bank mapped, before the game's
; AudioEngineMain, so a request is seen before that routine clears it.
Tick:
    lda MusicSuspendFlag
    beq @live
    ; AudioEngineMain silences the APU through $4015 when this is set, which
    ; empties the pulse length counters: have the high period bytes rewritten.
    lda #$80
    sta famistudio_pulse1_prev
    sta famistudio_pulse2_prev
    rts
@live:
    lda MusicRequest
    beq @tick
    bmi @other
    cmp #MUSIC_ID
    beq @start
@other:
    ; A stop, or another track: the game's sequencer answers it and silences
    ; the channels. Clearing the ID is what lets the sequencer run again.
    lda PlayingMusicID
    cmp #MUSIC_ID
    bne @done
    lda #0
    sta PlayingMusicID
@done:
    rts
@start:
    ; The engine's RAM is battery backed and holds whatever the last session
    ; left; famistudio_init does not write all of it (the output buffer, for
    ; one, which the frame's copy to the APU reads).
    ldx #0
    txa
@clear:
    sta __FSRAM_RUN__,x
    inx
    cpx #<__FSRAM_SIZE__
    bne @clear
    jsr SaveZeroPage
    lda #1  ; NTSC
    ldx #<SongData
    ldy #>SongData
    jsr famistudio_init
    lda #0
    jsr famistudio_music_play
    jsr RestoreZeroPage
    lda #MUSIC_ID
    sta PlayingMusicID
    lda #0
    sta MusicRequest  ; the game's sequencer must not start its own track
@tick:
    lda PlayingMusicID
    cmp #MUSIC_ID
    bne @done
    jsr SaveZeroPage
    jsr famistudio_update
RestoreZeroPage:
    ldx #ZP_SIZE - 1
@loop:
    lda SavedZeroPage,x
    sta <famistudio_r0,x
    dex
    bpl @loop
    rts

SaveZeroPage:
    ldx #ZP_SIZE - 1
@loop:
    lda <famistudio_r0,x
    sta SavedZeroPage,x
    dex
    bpl @loop
    rts

.segment "FSRAM"
SavedZeroPage: .res ZP_SIZE

.include "{ENGINE_SOURCE}"

.segment "FSCODE"
SongData = {{song_label}}
.include "song.s"
"""

_LINK = f"""\
MEMORY {{
  ZP:  start = ${ZP_ORIGIN:04X}, size = ${ZP_SIZE:04X}, type = rw, file = "";
  RAM: start = ${RAM_ORIGIN:04X}, size = ${RAM_LIMIT - RAM_ORIGIN + 1:04X}, type = rw, file = "";
  PRG: start = ${BLOB_ORIGIN:04X}, size = ${BLOB_END - BLOB_ORIGIN + 1:04X}, type = ro, file = %O, fill = no;
}}
SEGMENTS {{
  FSZP:   load = ZP,  type = zp;
  FSRAM:  load = RAM, type = bss, define = yes;
  FSCODE: load = PRG, type = ro;
}}
"""

# The engine's copy from its output buffer to the APU, channel by channel. Each
# edit is (the line it goes in front of, the lines added). While one of the
# game's effects holds a channel the copy for that channel is skipped.
_PULSE_GATE = """\
    lda {slot}
    beq @golf_{name}_free
    lda #$80                       ; rewrite the high period byte afterwards
    sta {prev}
    bne {skip}
@golf_{name}_free:
    lda #$08                       ; an effect may have left the sweep unit on
    sta {sweep}
"""
# Square 1, which a FamiStudio song usually gives the tune, plays on the hardware's
# pulse 2, and Square 2 on pulse 1: the engine's register names are given each
# other's addresses. The game's own music does the same (docs/music_format.md),
# because the menu effects all take pulse 1.
_PULSE_REGISTERS = {
    "FAMISTUDIO_APU_PL1_VOL": 0x4004,
    "FAMISTUDIO_APU_PL1_SWEEP": 0x4005,
    "FAMISTUDIO_APU_PL1_LO": 0x4006,
    "FAMISTUDIO_APU_PL1_HI": 0x4007,
    "FAMISTUDIO_APU_PL2_VOL": 0x4000,
    "FAMISTUDIO_APU_PL2_SWEEP": 0x4001,
    "FAMISTUDIO_APU_PL2_LO": 0x4002,
    "FAMISTUDIO_APU_PL2_HI": 0x4003,
}
_GATES = (
    (
        "    lda famistudio_output_buf      ; Pulse 1 volume\n",
        _PULSE_GATE.format(
            slot="SfxSlot2Playing",
            name="pulse1",
            prev="famistudio_pulse1_prev",
            skip="@no_pulse1_upd",
            sweep="FAMISTUDIO_APU_PL1_SWEEP",
        ),
    ),
    (
        "    lda famistudio_output_buf+3    ; Pulse 2 volume\n",
        _PULSE_GATE.format(
            slot="SfxSlot1Playing",
            name="pulse2",
            prev="famistudio_pulse2_prev",
            skip="@no_pulse2_upd",
            sweep="FAMISTUDIO_APU_PL2_SWEEP",
        ),
    ),
    (
        "    lda famistudio_output_buf+9    ; Noise volume\n",
        "    lda SfxSlot3Playing\n"
        "    bne @golf_noise_held\n"
        "    lda #$00                       ; an effect may have run the length counter out\n"
        "    sta FAMISTUDIO_APU_NOISE_HI\n",
    ),
)
_NOISE_END = (
    "    sta FAMISTUDIO_APU_NOISE_LO\n\n.endif\n",
    "    sta FAMISTUDIO_APU_NOISE_LO\n@golf_noise_held:\n\n.endif\n",
)


class FamiStudioBuildError(Exception):
    """The engine source, the song or the toolchain is not what the build expects."""


@dataclass(frozen=True)
class EngineBuild:
    blob: bytes
    code_size: int  # the wrapper and the engine
    song_size: int
    ram_size: int
    symbols: dict[str, int]

    @property
    def free(self) -> int:
        return BLOB_END - BLOB_ORIGIN + 1 - len(self.blob)


def gate_engine_source(source: str) -> str:
    """The engine source with its pulse channels swapped and its APU copy
    yielding to the game's sound effects."""

    def once(text: str, anchor: str) -> None:
        if text.count(anchor) != 1:
            raise FamiStudioBuildError(
                f"expected one {anchor.strip()!r} in {ENGINE_SOURCE}, found "
                f"{text.count(anchor)}: the engine source is not the version this "
                "was written against (FamiStudio 4.5.3)"
            )

    for name, address in _PULSE_REGISTERS.items():
        source, found = re.subn(
            rf"^({name}\s*=\s*)\$40\d\d$", rf"\g<1>${address:04X}", source, flags=re.M
        )
        if found != 1:
            raise FamiStudioBuildError(
                f"expected one definition of {name} in {ENGINE_SOURCE}, found {found}: "
                "the engine source is not the version this was written against "
                "(FamiStudio 4.5.3)"
            )
    for anchor, added in _GATES:
        once(source, anchor)
        source = source.replace(anchor, added + anchor)
    once(source, _NOISE_END[0])
    return source.replace(*_NOISE_END)


def _run(args: list[str], cwd: Path) -> None:
    tool = shutil.which(args[0])
    if tool is None:
        raise FamiStudioBuildError(f"{args[0]} is not on the path (install cc65)")
    done = subprocess.run([tool, *args[1:]], cwd=cwd, capture_output=True, text=True)
    if done.returncode:
        raise FamiStudioBuildError(f"{args[0]} failed:\n{done.stdout}{done.stderr}")


def build(engine_dir: Path, song: Path) -> EngineBuild:
    """Assemble the engine in ``engine_dir`` with the exported ``song``."""
    source = engine_dir / ENGINE_SOURCE
    if not source.is_file():
        raise FamiStudioBuildError(f"no {ENGINE_SOURCE} in {engine_dir}")
    song_text = song.read_text()
    labels = re.findall(r"^(music_data_\w+):", song_text, re.MULTILINE)
    if len(labels) != 1:
        raise FamiStudioBuildError(
            f"{song} is not a FamiStudio Music Code export in ca65 format "
            f"(found {len(labels)} music_data labels)"
        )
    if "@samples:" in song_text and re.search(r"@samples:\s*\n\s*\.byte", song_text):
        raise FamiStudioBuildError(
            f"{song} uses DPCM samples, which this build leaves to the game"
        )

    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        (work / ENGINE_SOURCE).write_text(gate_engine_source(source.read_text()))
        shutil.copytree(engine_dir / "NoteTables", work / "NoteTables")
        (work / "song.s").write_text(song_text)
        (work / "blob.s").write_text(_CONFIG.format(song_label=labels[0]))
        (work / "link.cfg").write_text(_LINK)
        _run(["ca65", "-g", "blob.s", "-o", "blob.o"], work)
        _run(
            ["ld65", "-C", "link.cfg", "-m", "blob.map", "-Ln", "blob.lbl"]
            + ["-o", "blob.bin", "blob.o"],
            work,
        )
        blob = (work / "blob.bin").read_bytes()
        symbols = {}
        for line in (work / "blob.lbl").read_text().splitlines():
            _, address, name = line.split()
            symbols[name.lstrip(".")] = int(address, 16)
        ram = re.search(
            r"^FSRAM\s+\w+\s+\w+\s+(\w+)", (work / "blob.map").read_text(), re.M
        )

    ram_size = int(ram.group(1), 16) if ram else 0
    if not 0 < ram_size < 0x100:
        raise FamiStudioBuildError(
            f"the engine's RAM is {ram_size} bytes; Tick clears it with an 8-bit count"
        )
    if symbols.get("Tick") != BLOB_ORIGIN:
        raise FamiStudioBuildError("Tick is not at the start of the blob")
    song_at = symbols[labels[0]]
    return EngineBuild(
        blob=blob,
        code_size=song_at - BLOB_ORIGIN,
        song_size=BLOB_ORIGIN + len(blob) - song_at,
        ram_size=ram_size,
        symbols=symbols,
    )
